import type { AlertStatus, EventOutcome, IncidentStatus, Severity } from "../../types/soc";

const SEVERITY_STYLES: Record<Severity, string> = {
  critical: "bg-red-500/15 text-red-300 border-red-500/40",
  high: "bg-orange-500/15 text-orange-300 border-orange-500/40",
  medium: "bg-amber-500/15 text-amber-300 border-amber-500/40",
  low: "bg-sky-500/15 text-sky-300 border-sky-500/40",
  informational: "bg-slate-500/15 text-slate-300 border-slate-500/40",
};

const ALERT_STATUS_STYLES: Record<AlertStatus, string> = {
  new: "bg-cyan-500/15 text-cyan-300 border-cyan-500/40",
  investigating: "bg-purple-500/15 text-purple-300 border-purple-500/40",
  resolved: "bg-emerald-500/15 text-emerald-300 border-emerald-500/40",
  false_positive: "bg-slate-600/20 text-slate-300 border-slate-500/40",
};

const INCIDENT_STATUS_STYLES: Record<IncidentStatus, string> = {
  open: "bg-red-500/15 text-red-300 border-red-500/40",
  investigating: "bg-purple-500/15 text-purple-300 border-purple-500/40",
  containment: "bg-orange-500/15 text-orange-300 border-orange-500/40",
  eradication: "bg-amber-500/15 text-amber-300 border-amber-500/40",
  recovery: "bg-sky-500/15 text-sky-300 border-sky-500/40",
  closed: "bg-emerald-500/15 text-emerald-300 border-emerald-500/40",
};

const OUTCOME_STYLES: Record<EventOutcome, string> = {
  success: "bg-emerald-500/15 text-emerald-300 border-emerald-500/40",
  failure: "bg-rose-500/15 text-rose-300 border-rose-500/40",
  unknown: "bg-slate-500/15 text-slate-300 border-slate-500/40",
};

export function SeverityBadge({ severity }: { severity: Severity }) {
  return (
    <span
      className={`inline-flex items-center px-2 py-0.5 rounded text-xs font-semibold uppercase tracking-wide border ${
        SEVERITY_STYLES[severity] || SEVERITY_STYLES.informational
      }`}
    >
      {severity}
    </span>
  );
}

export function AlertStatusBadge({ status }: { status: AlertStatus }) {
  return (
    <span
      className={`inline-flex items-center px-2 py-0.5 rounded text-xs font-medium border ${
        ALERT_STATUS_STYLES[status] || ALERT_STATUS_STYLES.new
      }`}
    >
      {status.replace("_", " ")}
    </span>
  );
}

export function IncidentStatusBadge({ status }: { status: IncidentStatus }) {
  return (
    <span
      className={`inline-flex items-center px-2.5 py-0.5 rounded text-xs font-semibold uppercase tracking-wide border ${
        INCIDENT_STATUS_STYLES[status] || INCIDENT_STATUS_STYLES.open
      }`}
    >
      {status}
    </span>
  );
}

export function OutcomeBadge({ outcome }: { outcome: EventOutcome }) {
  return (
    <span
      className={`inline-flex items-center px-2 py-0.5 rounded text-xs font-medium border ${
        OUTCOME_STYLES[outcome] || OUTCOME_STYLES.unknown
      }`}
    >
      {outcome}
    </span>
  );
}

