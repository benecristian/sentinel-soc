"""Incident report generation (JSON and PDF).

Security note: ReportLab's `Paragraph` interprets XML markup (`<b>`, `<font>`,
etc.). Any attacker-controlled string (log payloads, URLs, user agents) or user
note MUST be XML-escaped via `xml.sax.saxutils.escape` before being passed to
`Paragraph`.
"""

from __future__ import annotations

import io
import uuid
from datetime import UTC, datetime
from typing import Any
from xml.sax.saxutils import escape as xml_escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
from sqlalchemy import select
from sqlalchemy.orm import Session, selectinload

from app.core.errors import NotFoundError
from app.models import (
    Alert,
    DetectionRule,
    Incident,
    InvestigationNote,
    MitreTechnique,
    SecurityEvent,
    alert_events,
)


def build_incident_report_data(db: Session, incident_id: uuid.UUID) -> dict[str, Any]:
    incident = db.scalar(
        select(Incident)
        .where(Incident.id == incident_id)
        .options(
            selectinload(Incident.lead_analyst),
            selectinload(Incident.timeline),
            selectinload(Incident.alert_links),
        )
    )
    if incident is None:
        raise NotFoundError("Incident not found")

    alert_ids = [link.alert_id for link in incident.alert_links]
    alerts: list[Alert] = []
    if alert_ids:
        alerts = list(
            db.scalars(
                select(Alert).where(Alert.id.in_(alert_ids)).order_by(Alert.first_seen.asc())
            )
        )

    notes = list(
        db.scalars(
            select(InvestigationNote)
            .where(InvestigationNote.incident_id == incident.id)
            .options(selectinload(InvestigationNote.author))
            .order_by(InvestigationNote.created_at.asc())
        )
    )

    # Collect related events, MITRE techniques, and remediation recommendations from rules
    event_rows: list[SecurityEvent] = []
    if alert_ids:
        event_rows = list(
            db.scalars(
                select(SecurityEvent)
                .join(alert_events, alert_events.c.event_id == SecurityEvent.id)
                .where(alert_events.c.alert_id.in_(alert_ids))
                .order_by(SecurityEvent.timestamp.asc())
                .limit(200)
            )
        )

    technique_ids = sorted({a.mitre_technique_id for a in alerts if a.mitre_technique_id})
    techniques: list[MitreTechnique] = []
    if technique_ids:
        techniques = list(
            db.scalars(
                select(MitreTechnique)
                .where(MitreTechnique.id.in_(technique_ids))
                .options(selectinload(MitreTechnique.tactics))
            )
        )

    rule_ids = sorted({a.rule_id for a in alerts})
    rule_remediations: list[str] = list(incident.recommended_actions or [])
    if rule_ids:
        rules = list(db.scalars(select(DetectionRule).where(DetectionRule.id.in_(rule_ids))))
        for r in rules:
            for step in r.remediation_steps or []:
                if step not in rule_remediations:
                    rule_remediations.append(step)

    contains_synthetic = any(ev.is_synthetic for ev in event_rows)

    return {
        "report_metadata": {
            "generated_at": datetime.now(UTC).isoformat(),
            "platform": "SENTINEL SOC",
            "contains_synthetic_data": contains_synthetic,
            "synthetic_notice": (
                "SYNTHETIC DEMONSTRATION DATA: One or more evidence events in this "
                "report were generated by the SENTINEL SOC simulation engine."
                if contains_synthetic
                else None
            ),
        },
        "incident": {
            "id": str(incident.id),
            "reference": incident.reference,
            "title": incident.title,
            "description": incident.description,
            "severity": incident.severity,
            "status": incident.status,
            "lead_analyst": (
                {
                    "id": str(incident.lead_analyst.id),
                    "username": incident.lead_analyst.username,
                    "display_name": incident.lead_analyst.display_name,
                }
                if incident.lead_analyst
                else None
            ),
            "created_at": incident.created_at.isoformat(),
            "updated_at": incident.updated_at.isoformat(),
            "closed_at": incident.closed_at.isoformat() if incident.closed_at else None,
            "findings": incident.findings,
            "resolution_summary": incident.resolution_summary,
        },
        "related_alerts": [
            {
                "id": str(a.id),
                "reference": a.reference,
                "rule_id": a.rule_id,
                "rule_name": a.rule_name,
                "severity": a.severity,
                "status": a.status,
                "title": a.title,
                "description": a.description,
                "source_ip": str(a.source_ip) if a.source_ip else None,
                "username": a.username,
                "hostname": a.hostname,
                "mitre_technique_id": a.mitre_technique_id,
                "event_count": a.event_count,
                "first_seen": a.first_seen.isoformat(),
                "last_seen": a.last_seen.isoformat(),
                "evidence": a.evidence,
            }
            for a in alerts
        ],
        "mitre_mapping": [
            {
                "technique_id": t.id,
                "name": t.name,
                "url": t.url,
                "tactics": [tac.name for tac in t.tactics],
            }
            for t in techniques
        ],
        "timeline": [
            {
                "occurred_at": entry.occurred_at.isoformat(),
                "entry_type": entry.entry_type,
                "summary": entry.summary,
                "details": entry.details,
            }
            for entry in incident.timeline
        ],
        "investigation_notes": [
            {
                "id": str(n.id),
                "author": n.author.display_name if n.author else "Analyst",
                "created_at": n.created_at.isoformat(),
                "body": n.body,
            }
            for n in notes
        ],
        "evidence_events_sample": [
            {
                "id": str(e.id),
                "timestamp": e.timestamp.isoformat(),
                "event_type": e.event_type,
                "event_action": e.event_action,
                "event_outcome": e.event_outcome,
                "source_ip": str(e.source_ip) if e.source_ip else None,
                "destination_ip": str(e.destination_ip) if e.destination_ip else None,
                "username": e.username,
                "hostname": e.hostname,
                "raw_event": e.raw_event[:500],
                "is_synthetic": e.is_synthetic,
            }
            for e in event_rows[:25]
        ],
        "recommended_remediation": rule_remediations,
    }


def _safe(text: Any) -> str:
    return xml_escape(str(text if text is not None else "—"))


def render_incident_pdf(report: dict[str, Any]) -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title=f"SENTINEL SOC Incident Report - {report['incident']['reference']}",
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Heading1"],
        fontSize=16,
        leading=20,
        textColor=colors.HexColor("#0f172a"),
        spaceAfter=6,
    )
    h2_style = ParagraphStyle(
        "SectionHeader",
        parent=styles["Heading2"],
        fontSize=12,
        leading=15,
        textColor=colors.HexColor("#0f172a"),
        spaceBefore=12,
        spaceAfter=6,
    )
    body_style = ParagraphStyle(
        "Body",
        parent=styles["Normal"],
        fontSize=9.5,
        leading=13,
        textColor=colors.HexColor("#1e293b"),
    )
    mono_style = ParagraphStyle(
        "Mono",
        parent=styles["Code"],
        fontName="Courier",
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#0f172a"),
    )

    inc = report["incident"]
    meta = report["report_metadata"]
    story: list[Any] = []

    story.append(
        Paragraph(
            f"SENTINEL SOC — Incident Report ({_safe(inc['reference'])})",
            title_style,
        )
    )
    story.append(
        Paragraph(
            f"<b>Title:</b> {_safe(inc['title'])} &nbsp;&nbsp;|&nbsp;&nbsp; "
            f"<b>Severity:</b> {_safe(inc['severity']).upper()} &nbsp;&nbsp;|&nbsp;&nbsp; "
            f"<b>Status:</b> {_safe(inc['status']).upper()}",
            body_style,
        )
    )
    if meta.get("contains_synthetic_data"):
        story.append(Spacer(1, 4))
        story.append(
            Paragraph(
                f"<b>Notice:</b> {_safe(meta.get('synthetic_notice'))}",
                body_style,
            )
        )
    story.append(Spacer(1, 8))

    # 1. Overview table
    lead = inc["lead_analyst"]["display_name"] if inc.get("lead_analyst") else "Unassigned"
    overview_rows = [
        ["Reference", _safe(inc["reference"]), "Severity", _safe(inc["severity"]).upper()],
        ["Status", _safe(inc["status"]).upper(), "Lead Analyst", _safe(lead)],
        [
            "Created (UTC)",
            _safe(inc["created_at"]),
            "Closed (UTC)",
            _safe(inc.get("closed_at") or "Open"),
        ],
    ]
    overview_table = Table(overview_rows, colWidths=[32 * mm, 55 * mm, 32 * mm, 55 * mm])
    overview_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f1f5f9")),
                ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#f1f5f9")),
                ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
                ("FONTNAME", (2, 0), (2, -1), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 8.5),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ("PADDING", (0, 0), (-1, -1), 5),
            ]
        )
    )
    story.append(overview_table)

    # 2. Summary & Findings
    story.append(Paragraph("1. Incident Overview & Findings", h2_style))
    story.append(
        Paragraph(
            f"<b>Description:</b> {_safe(inc['description'] or 'None provided.')}", body_style
        )
    )
    story.append(Spacer(1, 4))
    story.append(
        Paragraph(
            f"<b>Investigation Findings:</b> {_safe(inc['findings'] or 'Pending investigation.')}",
            body_style,
        )
    )
    if inc.get("resolution_summary"):
        story.append(Spacer(1, 4))
        story.append(
            Paragraph(f"<b>Resolution Summary:</b> {_safe(inc['resolution_summary'])}", body_style)
        )

    # 3. Related Alerts
    story.append(Paragraph("2. Linked Security Alerts", h2_style))
    alerts = report["related_alerts"]
    if alerts:
        for a in alerts:
            story.append(
                Paragraph(
                    f"• <b>{_safe(a['reference'])} [{_safe(a['severity']).upper()}]</b> "
                    f"{_safe(a['title'])} — Rule: {_safe(a['rule_id'])} "
                    f"(Events: {_safe(a['event_count'])}, MITRE: {_safe(a['mitre_technique_id'])})",
                    body_style,
                )
            )
    else:
        story.append(Paragraph("No alerts linked to this incident.", body_style))

    # 4. MITRE ATT&CK Mapping
    story.append(Paragraph("3. MITRE ATT&CK Mapping", h2_style))
    if report["mitre_mapping"]:
        for m in report["mitre_mapping"]:
            tactics_str = ", ".join(m["tactics"])
            story.append(
                Paragraph(
                    f"• <b>{_safe(m['technique_id'])} — {_safe(m['name'])}</b> "
                    f"(Tactics: {_safe(tactics_str)})",
                    body_style,
                )
            )
    else:
        story.append(Paragraph("No MITRE ATT&CK techniques mapped.", body_style))

    # 5. Incident Timeline
    story.append(Paragraph("4. Incident Response Timeline", h2_style))
    for entry in report["timeline"]:
        story.append(
            Paragraph(
                f"• <b>{_safe(entry['occurred_at'])}</b> [{_safe(entry['entry_type'])}]: "
                f"{_safe(entry['summary'])}",
                body_style,
            )
        )

    # 6. Investigation Notes
    if report["investigation_notes"]:
        story.append(Paragraph("5. Analyst Investigation Notes", h2_style))
        for n in report["investigation_notes"]:
            story.append(
                Paragraph(
                    f"• <b>{_safe(n['author'])} ({_safe(n['created_at'])}):</b> {_safe(n['body'])}",
                    body_style,
                )
            )

    # 7. Evidence Sample
    if report["evidence_events_sample"]:
        story.append(Paragraph("6. Sample Evidence Events", h2_style))
        for ev in report["evidence_events_sample"][:10]:
            story.append(Paragraph(_safe(ev["raw_event"]), mono_style))
            story.append(Spacer(1, 2))

    # 8. Recommended Remediation
    story.append(Paragraph("7. Recommended Remediation Actions", h2_style))
    if report["recommended_remediation"]:
        for step in report["recommended_remediation"]:
            story.append(Paragraph(f"• {_safe(step)}", body_style))
    else:
        story.append(Paragraph("No remediation steps recorded.", body_style))

    doc.build(story)
    return buffer.getvalue()
