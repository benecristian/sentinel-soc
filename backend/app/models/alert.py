from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    CheckConstraint,
    Column,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    Sequence,
    String,
    Table,
    Text,
    Uuid,
    text,
)
from sqlalchemy.dialects.postgresql import INET, JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base, TimestampMixin, enum_check
from app.domain.enums import AlertStatus, Severity
from app.models.detection import DetectionRule
from app.models.mitre import MitreTechnique
from app.models.user import User

# Human-friendly, monotonically increasing references (ALR-000042) generated by
# PostgreSQL itself, so they are unique even under concurrent inserts.
alert_reference_seq = Sequence("alert_reference_seq", metadata=Base.metadata)

alert_events = Table(
    "alert_events",
    Base.metadata,
    Column("alert_id", Uuid, ForeignKey("alerts.id", ondelete="CASCADE"), primary_key=True),
    Column(
        "event_id", Uuid, ForeignKey("security_events.id", ondelete="CASCADE"), primary_key=True
    ),
    Index("ix_alert_events_event_id", "event_id"),
)


class Alert(TimestampMixin, Base):
    """A detection finding awaiting analyst triage."""

    __tablename__ = "alerts"
    __table_args__ = (
        enum_check("severity", Severity),
        enum_check("status", AlertStatus),
        CheckConstraint("event_count >= 0", name="event_count_non_negative"),
        CheckConstraint("first_seen <= last_seen", name="seen_order"),
        # At most ONE open alert per (rule, entity). Repeated activity updates the
        # existing alert instead of flooding the queue (alert fatigue is a real
        # SOC problem). Enforced by the database, so it holds under concurrency.
        Index(
            "uq_alerts_open_dedup_key",
            "dedup_key",
            unique=True,
            postgresql_where=text("status IN ('new', 'investigating')"),
        ),
        Index("ix_alerts_status_severity", "status", "severity"),
        Index("ix_alerts_created_at", "created_at"),
        Index("ix_alerts_source_ip", "source_ip"),
        Index("ix_alerts_rule_id", "rule_id"),
        Index("ix_alerts_username", "username"),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    reference: Mapped[str] = mapped_column(
        String(16),
        nullable=False,
        unique=True,
        server_default=text("'ALR-' || lpad(nextval('alert_reference_seq')::text, 6, '0')"),
    )
    rule_id: Mapped[str] = mapped_column(
        String(32), ForeignKey("detection_rules.id", ondelete="RESTRICT"), nullable=False
    )
    # Snapshot of the rule name at detection time (rules can be renamed later).
    rule_name: Mapped[str] = mapped_column(String(128), nullable=False)
    severity: Mapped[str] = mapped_column(String(16), nullable=False)
    status: Mapped[str] = mapped_column(
        String(20), nullable=False, default=AlertStatus.NEW.value, server_default="new"
    )
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=False)
    source_ip: Mapped[str | None] = mapped_column(INET)
    username: Mapped[str | None] = mapped_column(String(256))
    hostname: Mapped[str | None] = mapped_column(String(255))
    mitre_technique_id: Mapped[str | None] = mapped_column(
        String(16), ForeignKey("mitre_techniques.id", ondelete="SET NULL")
    )
    evidence: Mapped[dict[str, Any]] = mapped_column(
        JSONB, nullable=False, default=dict, server_default=text("'{}'::jsonb")
    )
    dedup_key: Mapped[str] = mapped_column(String(64), nullable=False)
    event_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0, server_default="0")
    first_seen: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    last_seen: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    assigned_to: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("users.id", ondelete="SET NULL")
    )
    resolved_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    rule: Mapped[DetectionRule] = relationship()
    mitre_technique: Mapped[MitreTechnique | None] = relationship()
    assignee: Mapped[User | None] = relationship()
